"""Generate docs/tools.md from the server's tool, resource and prompt definitions.

python scripts/gen_tool_docs.py          # write docs/tools.md
python scripts/gen_tool_docs.py --check  # exit 1 if docs/tools.md is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import anyio
from mcp import Client

from emhub_tomo_mcp.config import load_settings
from emhub_tomo_mcp.server import build_server
from emhub_tomo_mcp.services import Services

DOC = Path(__file__).resolve().parents[1] / "docs" / "tools.md"


def _type(schema: dict[str, Any]) -> str:
    if "anyOf" in schema:
        return " or ".join(_type(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if schema.get("type") == "array":
        return f"list of {_type(schema.get('items', {}))}"
    return str(schema.get("type", "any"))


def _limits(schema: dict[str, Any]) -> str:
    parts = []
    for key, label in (
        ("minimum", "≥"),
        ("maximum", "≤"),
        ("minLength", "min length"),
        ("maxLength", "max length"),
        ("minItems", "min items"),
        ("maxItems", "max items"),
        ("pattern", "pattern"),
    ):
        for candidate in [schema, *schema.get("anyOf", [])]:
            if key in candidate:
                value = candidate[key]
                parts.append(f"{label} `{value}`" if key == "pattern" else f"{label} {value}")
    return ", ".join(parts)


async def render() -> str:
    settings = load_settings(
        {"EMHUB_SERVER_URL": "http://127.0.0.1:1", "EMHUB_TOMO_MCP_ACCESS": "admin"}
    ).settings
    services = Services.create(settings)
    lines = [
        "# Tool reference",
        "",
        "*Generated by `scripts/gen_tool_docs.py` from the server code; do not edit by hand.*",
        "",
        "The first eleven tools are read-only and always available. The others exist only "
        "with `EMHUB_TOMO_MCP_ACCESS=operate` (`delete_jobs`: `admin`); `run_job`, `stop_jobs` "
        "and `delete_jobs` are annotated as destructive. Each tool returns structured content "
        "(the fields of its output schema) and the same data as JSON after a one-line summary "
        "in its text content.",
        "",
    ]
    async with Client(build_server(services)) as client:
        for tool in (await client.list_tools()).tools:
            lines += [f"## `{tool.name}`", "", (tool.description or "").strip(), ""]
            props = tool.input_schema.get("properties", {})
            required = set(tool.input_schema.get("required", []))
            if props:
                lines += ["| Argument | Type | Default | Notes |", "|---|---|---|---|"]
                for name, schema in props.items():
                    default = "required" if name in required else f"`{schema.get('default')}`"
                    notes = " ".join(
                        p for p in (schema.get("description", ""), _limits(schema)) if p
                    )
                    lines.append(f"| `{name}` | {_type(schema)} | {default} | {notes} |")
                lines.append("")
            output = (tool.output_schema or {}).get("properties", {})
            if output:
                lines += ["Returns: " + ", ".join(f"`{k}`" for k in output) + ".", ""]
        lines += ["## Resources", ""]
        for res in (await client.list_resources()).resources:
            lines.append(f"- `{res.uri}`: {res.description}")
        for tpl in (await client.list_resource_templates()).resource_templates:
            lines.append(f"- `{tpl.uri_template}`: {tpl.description}")
        lines += ["", "## Prompts", ""]
        for prompt in (await client.list_prompts()).prompts:
            args = ", ".join(a.name for a in prompt.arguments or [])
            lines.append(f"- `{prompt.name}({args})`: {prompt.description}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = anyio.run(render)
    if args.check:
        if not DOC.exists() or DOC.read_text() != text:
            print(f"{DOC} is out of date; run scripts/gen_tool_docs.py", file=sys.stderr)
            return 1
        return 0
    DOC.parent.mkdir(exist_ok=True)
    DOC.write_text(text)
    print(f"Wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
